"""
====================================================================
Monte Carlo Dropout for Epistemic Uncertainty
====================================================================

Physics-Informed 3D Encoder-Decoder Framework
with Predictive Uncertainty for Seismic Data Reconstruction

ACOUSTIC-WAVE-EQUATION VERSION
------------------------------

Purpose
-------
Monte Carlo (MC) Dropout approximates epistemic uncertainty by
performing multiple stochastic forward passes with dropout active.

The network returns three outputs:

    1. reconstructed_cube
       Reconstructed seismic volume.

    2. pressure_wavefield
       Acoustic pressure wavefield associated with the acoustic
       wave-equation physics formulation.

    3. log_variance
       Predicted log aleatoric variance for the reconstruction.

This module estimates epistemic uncertainty for the reconstructed
seismic volume.

Aleatoric uncertainty is predicted separately by the network.

Predictive variance can be estimated as:

    predictive_variance = aleatoric_variance + epistemic_variance

Memory-efficient inference
--------------------------
The acoustic pressure wavefield can be extremely large.

For example, a float32 pressure tensor with shape

    [1, 1, 128, 64, 128, 128]

requires approximately 512 MiB of memory.

Consequently, this module does not retain pressure-wavefield samples
by default. The pressure output is still generated by the network,
but it is discarded after each forward pass when it is not required.

Set store_pressure_wavefield_samples=True only when the calling
application explicitly requires all pressure-wavefield samples.
This can consume substantial memory.

Compatibility
-------------
The three-output network architecture is unchanged.

Legacy result keys containing "travel_time" are retained as aliases
for the acoustic pressure-wavefield results. When pressure-wavefield
storage is disabled, these values are None.

New code should use the pressure_wavefield_* keys instead.

Input convention
----------------
Input:
    [B, C, D, H, W]

Reconstruction samples:
    [N, B, C, D, H, W]

Reconstruction mean and epistemic variance:
    [B, C, D, H, W]

====================================================================
"""

import torch
import torch.nn as nn


class MCDropout3D:
    """
    Monte Carlo Dropout estimator for epistemic uncertainty.

    Parameters
    ----------
    model : nn.Module
        Trained 3D encoder-decoder network returning:

            reconstructed_cube,
            pressure_wavefield,
            log_variance

    num_samples : int, default=20
        Number of stochastic forward passes. Must be at least 2.

    store_pressure_wavefield_samples : bool, default=False
        If True, retain and stack the complete pressure-wavefield
        output from every stochastic forward pass.

        WARNING:
        Pressure-wavefield sample storage can require several
        gigabytes of memory. Leave this False for reconstruction
        galleries and reconstruction-only uncertainty analysis.

    Notes
    -----
    The complete model is placed in evaluation mode, after which
    dropout layers are selectively activated.

    This prevents BatchNorm layers, if present, from updating their
    running statistics during MC inference.

    Original module training states are restored after inference,
    including when an exception occurs.
    """

    def __init__(
        self,
        model: nn.Module,
        num_samples: int = 20,
        store_pressure_wavefield_samples: bool = False,
    ):
        """Initialize the MC Dropout estimator."""

        # ---------------------------------------------------------
        # Validate model
        # ---------------------------------------------------------

        if not isinstance(model, nn.Module):
            raise TypeError(
                "model must be an instance of torch.nn.Module."
            )

        # ---------------------------------------------------------
        # Validate MC sample count
        # ---------------------------------------------------------

        if isinstance(num_samples, bool) or not isinstance(
            num_samples, int
        ):
            raise TypeError(
                "num_samples must be an integer."
            )

        if num_samples < 2:
            raise ValueError(
                "num_samples must be at least 2."
            )

        # ---------------------------------------------------------
        # Validate pressure-wavefield storage option
        # ---------------------------------------------------------

        if not isinstance(
            store_pressure_wavefield_samples, bool
        ):
            raise TypeError(
                "store_pressure_wavefield_samples must be a bool."
            )

        # ---------------------------------------------------------
        # Store configuration
        # ---------------------------------------------------------

        self.model = model
        self.num_samples = num_samples

        self.store_pressure_wavefield_samples = (
            store_pressure_wavefield_samples
        )

    # =============================================================
    # ENABLE MC DROPOUT
    # =============================================================

    def _enable_dropout(self):
        """
        Put the model into evaluation mode and activate dropout only.

        Returns
        -------
        dict
            Original training/evaluation state of every module.
        """

        # Save original state of every module.
        original_states = {
            module: module.training
            for module in self.model.modules()
        }

        # Set the complete model to evaluation mode.
        self.model.eval()

        # Activate only dropout layers.
        for module in self.model.modules():

            if isinstance(
                module,
                (
                    nn.Dropout,
                    nn.Dropout1d,
                    nn.Dropout2d,
                    nn.Dropout3d,
                ),
            ):
                module.train()

        return original_states

    # =============================================================
    # RESTORE MODEL STATE
    # =============================================================

    @staticmethod
    def _restore_model_state(original_states):
        """
        Restore the training/evaluation state of every module.
        """

        for module, training_state in original_states.items():
            module.training = training_state

    # =============================================================
    # STOCHASTIC FORWARD PASSES
    # =============================================================

    @torch.no_grad()
    def predict(self, x: torch.Tensor):
        """
        Perform multiple stochastic forward passes.

        Parameters
        ----------
        x : torch.Tensor
            Input seismic volume with shape [B, C, D, H, W].

        Returns
        -------
        dict
            Reconstruction samples, log-variance samples,
            predictive means, and reconstruction epistemic variance.

            Pressure-wavefield samples and statistics are returned
            only when store_pressure_wavefield_samples=True.
            Otherwise, pressure-related result values are None.

        Notes
        -----
        The network continues to produce all three outputs.
        This method only controls which outputs are retained.

        Reconstruction and log-variance samples are retained because
        they are required for the reconstruction uncertainty analysis.
        """

        # ---------------------------------------------------------
        # Validate input type
        # ---------------------------------------------------------

        if not isinstance(x, torch.Tensor):
            raise TypeError(
                "x must be a torch.Tensor."
            )

        # ---------------------------------------------------------
        # Validate input dimensionality
        # ---------------------------------------------------------

        if x.ndim != 5:
            raise ValueError(
                "x must have shape [B, C, D, H, W]. "
                f"Received {tuple(x.shape)}."
            )

        # ---------------------------------------------------------
        # Validate input values
        # ---------------------------------------------------------

        if not torch.isfinite(x).all().item():
            raise FloatingPointError(
                "x contains NaN or infinite values."
            )

        # ---------------------------------------------------------
        # Prepare sample storage
        # ---------------------------------------------------------

        reconstruction_samples = []
        log_variance_samples = []

        # Pressure-wavefield storage is optional because the tensors
        # can be much larger than the reconstruction tensors.
        pressure_wavefield_samples = (
            []
            if self.store_pressure_wavefield_samples
            else None
        )

        # ---------------------------------------------------------
        # Save and modify model states
        # ---------------------------------------------------------

        original_states = self._enable_dropout()

        try:

            # -----------------------------------------------------
            # Perform stochastic forward passes
            # -----------------------------------------------------

            for sample_index in range(self.num_samples):

                outputs = self.model(x)

                # -------------------------------------------------
                # Validate model output structure
                # -------------------------------------------------

                if not isinstance(outputs, (tuple, list)):
                    raise TypeError(
                        "The model must return a tuple or list "
                        "containing reconstruction, pressure_wavefield, "
                        "and log_variance."
                    )

                if len(outputs) != 3:
                    raise ValueError(
                        "The model must return exactly three outputs: "
                        "reconstruction, pressure_wavefield, "
                        "and log_variance."
                    )

                (
                    reconstructed_cube,
                    pressure_wavefield,
                    log_variance,
                ) = outputs

                # -------------------------------------------------
                # Validate output tensors
                # -------------------------------------------------

                output_tensors = (
                    ("reconstruction", reconstructed_cube),
                    ("pressure_wavefield", pressure_wavefield),
                    ("log_variance", log_variance),
                )

                for name, tensor in output_tensors:

                    if not isinstance(tensor, torch.Tensor):
                        raise TypeError(
                            f"{name} must be a torch.Tensor."
                        )

                    if not torch.isfinite(tensor).all().item():
                        raise FloatingPointError(
                            f"{name} contains NaN or infinite values."
                        )

                # -------------------------------------------------
                # Validate reconstruction shape
                # -------------------------------------------------

                if reconstructed_cube.shape != x.shape:
                    raise ValueError(
                        "Reconstruction shape must match input shape. "
                        f"Input: {tuple(x.shape)}, "
                        f"reconstruction: "
                        f"{tuple(reconstructed_cube.shape)}."
                    )

                # -------------------------------------------------
                # Validate log-variance shape
                # -------------------------------------------------

                if log_variance.shape != reconstructed_cube.shape:
                    raise ValueError(
                        "log_variance must have the same shape as "
                        "the reconstruction. "
                        f"Received {tuple(log_variance.shape)}."
                    )

                # -------------------------------------------------
                # Store reconstruction outputs
                # -------------------------------------------------

                reconstruction_samples.append(
                    reconstructed_cube
                )

                log_variance_samples.append(
                    log_variance
                )

                # -------------------------------------------------
                # Store pressure wavefield only when requested
                # -------------------------------------------------

                if self.store_pressure_wavefield_samples:

                    pressure_wavefield_samples.append(
                        pressure_wavefield
                    )

                # -------------------------------------------------
                # Release references to unused forward outputs
                # -------------------------------------------------

                # When pressure storage is disabled, the large
                # pressure tensor is not retained between passes.
                del outputs
                del reconstructed_cube
                del pressure_wavefield
                del log_variance

        finally:

            # -----------------------------------------------------
            # Always restore the original model state
            # -----------------------------------------------------

            self._restore_model_state(original_states)

        # =========================================================
        # STACK RECONSTRUCTION AND LOG-VARIANCE SAMPLES
        # =========================================================

        reconstruction_samples = torch.stack(
            reconstruction_samples,
            dim=0,
        )

        log_variance_samples = torch.stack(
            log_variance_samples,
            dim=0,
        )

        # =========================================================
        # RECONSTRUCTION PREDICTIVE MEANS
        # =========================================================

        reconstruction_mean = (
            reconstruction_samples.mean(dim=0)
        )

        log_variance_mean = (
            log_variance_samples.mean(dim=0)
        )

        # =========================================================
        # RECONSTRUCTION EPISTEMIC VARIANCE
        # =========================================================

        # Population variance across MC predictions:
        #
        #     sigma_epistemic^2 = mean((y_i - mean(y))^2)
        #
        # unbiased=False is appropriate for the empirical
        # predictive distribution represented by these samples.

        reconstruction_epistemic_variance = (
            reconstruction_samples.var(
                dim=0,
                unbiased=False,
            )
        )

        # =========================================================
        # OPTIONAL PRESSURE-WAVEFIELD STATISTICS
        # =========================================================

        pressure_wavefield_mean = None
        pressure_wavefield_epistemic_variance = None

        if self.store_pressure_wavefield_samples:

            pressure_wavefield_samples = torch.stack(
                pressure_wavefield_samples,
                dim=0,
            )

            pressure_wavefield_mean = (
                pressure_wavefield_samples.mean(dim=0)
            )

            pressure_wavefield_epistemic_variance = (
                pressure_wavefield_samples.var(
                    dim=0,
                    unbiased=False,
                )
            )

        # =========================================================
        # RETURN RESULTS
        # =========================================================

        # The legacy "travel_time" keys are retained temporarily
        # as compatibility aliases. They do NOT mean that the
        # acoustic pressure wavefield is a travel-time field.
        #
        # New code should use pressure_wavefield_* keys.

        return {
            # -----------------------------------------------------
            # Reconstruction outputs
            # -----------------------------------------------------

            "reconstruction_samples":
                reconstruction_samples,

            "reconstruction_mean":
                reconstruction_mean,

            "reconstruction_epistemic_variance":
                reconstruction_epistemic_variance,

            # -----------------------------------------------------
            # Aleatoric uncertainty outputs
            # -----------------------------------------------------

            "log_variance_samples":
                log_variance_samples,

            "log_variance_mean":
                log_variance_mean,

            # -----------------------------------------------------
            # Acoustic pressure-wavefield outputs
            # -----------------------------------------------------

            "pressure_wavefield_samples":
                pressure_wavefield_samples,

            "pressure_wavefield_mean":
                pressure_wavefield_mean,

            "pressure_wavefield_epistemic_variance":
                pressure_wavefield_epistemic_variance,

            # -----------------------------------------------------
            # Legacy compatibility aliases
            # -----------------------------------------------------

            "travel_time_samples":
                pressure_wavefield_samples,

            "travel_time_mean":
                pressure_wavefield_mean,

            "travel_time_epistemic_variance":
                pressure_wavefield_epistemic_variance,
        }